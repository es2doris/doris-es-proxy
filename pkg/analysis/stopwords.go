func resolveStopwords(raw any, pathKey string, pathVal string, defaultPreset string, ignoreCase bool, opts Options) (map[string]bool, error) {
	var words []string
	if pathVal != "" {
		lines, err := resolvePathSetting(pathKey, pathVal, opts)
		if err != nil {
			return nil, err
		}
		words = append(words, lines...)
	} else if raw == nil {
		if preset, ok := builtInStopwords[defaultPreset]; ok {
			words = preset
		}
	} else {
		switch v := raw.(type) {
		case string:
			key := strings.ToLower(strings.TrimSpace(v))
			if preset, ok := builtInStopwords[key]; ok {
				words = preset
			} else if strings.HasPrefix(key, "_") && strings.HasSuffix(key, "_") {
				return nil, newIllegalArgError(fmt.Sprintf("Unknown named stopword list [%s]", v))
			} else {
				words = []string{v}
			}
		default:
			list := extractStringSlice(raw)
			if len(list) == 1 {
				key := strings.ToLower(strings.TrimSpace(list[0]))
				if preset, ok := builtInStopwords[key]; ok {
					words = preset
				} else {
					words = list
				}
			} else {
				words = list
			}
		}
	}

	set := make(map[string]bool, len(words))
	for _, w := range words {
		if idx := strings.Index(w, "|"); idx >= 0 {
			w = strings.TrimSpace(w[:idx]) // Snowball stopword file comment format
		}
		if strings.HasPrefix(strings.TrimSpace(w), "#") {
			continue
		}
		if ignoreCase {
			set[strings.ToLower(w)] = true
		} else {
			set[w] = true
		}
	}
	return set, nil
}
